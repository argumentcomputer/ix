/// BLAKE3 of a fixed matrix in the exporter's `IXTLFX01` encoding, written
/// through `scratch`.
fn fixed_digest(
  scratch: &std::path::Path,
  rows: usize,
  width: usize,
  values: &[Scalar],
) -> String {
  lean::write_fixed(scratch, rows, width, values).unwrap();
  let digest =
    blake3::hash(&std::fs::read(scratch).unwrap()).to_hex().to_string();
  std::fs::remove_file(scratch).unwrap();
  digest
}

/// The checked-in Lean export (layout, exported graphs and shard circuit) is
/// adopted with this backend's fixed matrix, whose encoding has the digest of
/// the exported one; the exported shard circuit equals this crate's; the
/// honest witness proves and verifies; a changed output claim, a changed
/// exported template row and a changed label stride are refused.
#[test]
fn v2_one_shard_checked_in_lean_export() {
  let plan = plan();
  let compiler = Compiler::with_lookup_budget(&plan, Some(4)).unwrap();
  let args = EXPORT_ARGS.map(f);
  let record = plan.program().execute(ENTRY, args.to_vec()).unwrap();
  let public = plan.public_args(&record, ENTRY, &args).unwrap();
  let claim = plan.public_claim(ENTRY, &public, &record.output).unwrap();
  let config = config(&compiler, &record, 1, true);
  let dir = std::path::Path::new(EXPORT_DIR);
  let out: serde_json::Value =
    serde_json::from_slice(&std::fs::read(dir.join(EXPORT_LAYOUT)).unwrap())
      .unwrap();
  assert_eq!(out["format"], "ix-tiling-v2-layout-1");
  assert_eq!(out["shards"], 1);
  let expected =
    std::fs::read_to_string(dir.join(EXPORT_FIXED_DIGEST)).unwrap();

  let reference = Backend::new(&compiler, &plan, config.clone())
    .unwrap()
    .lean_reference()
    .unwrap();
  let scratch = std::env::temp_dir()
    .join(format!("ix-v2-checked-in-{}.bin", std::process::id()));
  let digest = fixed_digest(
    &scratch,
    reference.fixed_rows,
    reference.fixed_width,
    &reference.fixed,
  );
  assert_eq!(
    digest,
    expected.trim(),
    "this backend's fixed matrix differs from the exported one; regenerate the fixture"
  );
  let layout = |out: serde_json::Value| lean::Layout {
    out,
    fixed_rows: reference.fixed_rows,
    fixed_width: reference.fixed_width,
    fixed: reference.fixed.clone(),
    tables: vec![],
  };

  let mut tampered = out.clone();
  tampered["templates"][0]["rows"][0] = serde_json::json!("empty");
  assert!(
    Backend::from_lean(&compiler, &plan, config.clone(), layout(tampered))
      .is_err(),
    "changed template row"
  );
  let mut tampered = out.clone();
  tampered["labels_per_shard"] =
    serde_json::json!(tampered["labels_per_shard"].as_u64().unwrap() + 1);
  assert!(
    Backend::from_lean(&compiler, &plan, config.clone(), layout(tampered))
      .is_err(),
    "changed label stride"
  );

  let backend =
    Backend::from_lean(&compiler, &plan, config, layout(out)).unwrap();
  assert_eq!(backend.shards, 1);
  let check = backend.rust_cross_check().unwrap();
  assert_eq!(check["narrow_circuit_equal"], true, "{check}");
  let (traces, key) = backend.witness(&record, ENTRY, &args).unwrap();
  let claims = backend.claims(&claim, key);
  backend.check_lean_request(&claims).unwrap();
  let s = setup(&backend);
  native_check(&s.inputs, &s.shared, &traces, &claims).unwrap();
  assert!(
    accepts(&s, traces.clone(), &claims),
    "honest witness under the checked-in export"
  );
  let mut wrong = claims.clone();
  *wrong.last_mut().unwrap().last_mut().unwrap() += Scalar::ONE;
  assert!(!accepts(&s, traces, &wrong), "changed output accepted");
}

