fn plan() -> TracePlan<'static, Bn254> {
  let package = WidePackage::decode(include_bytes!(
    "../../aiur/tests/fixtures/bn254-trace.ixa"
  ))
  .unwrap();
  let mut trace = package.trace.unwrap();
  trace.groups.clear();
  let mut checked: CheckedProgram<Bn254> =
    package.program.check_with(Bn254).unwrap();
  checked.track_depth(&trace).unwrap();
  TracePlan::new(Arc::new(checked), trace).unwrap()
}

fn f(v: u64) -> Scalar {
  Bn254.from_u64(v)
}

fn config(
  compiler: &Compiler<'_, '_>,
  record: &Execution<Bn254>,
  shards: usize,
  offsets: bool,
) -> Config {
  let raw = compiler.raw_row_counts(record).unwrap();
  let nf = compiler.function_circuits();
  let roms = compiler.names().iter().filter(|n| n.starts_with("<ROM:")).count();
  Config {
    width: 8,
    // Capacities divisible by the shard count, with two spares per shard:
    // every shard holds real and spare instances.
    capacities: raw[..nf]
      .iter()
      .map(|&n| shards * n.div_ceil(shards) + 2 * shards)
      .collect(),
    rom_capacities: raw[raw.len() - roms..].iter().map(|&n| n + 1).collect(),
    log_shard_rows: 20,
    shards: Some(shards),
    lookup_budget: 2,
    unroll_compress: true,
    shard_offsets: offsets,
    entry: Some(ENTRY.into()),
  }
}

fn eval(e: &Expr<Scalar>, main: &[Scalar], fixed: &[Scalar]) -> Scalar {
  match e {
    Expr::Const(c) => *c,
    Expr::Var(c) => match (c.source, c.offset) {
      (Source::Main, RowOffset::Current) => main[c.index as usize],
      (Source::Preprocessed, RowOffset::Current) => fixed[c.index as usize],
      _ => unreachable!(),
    },
    Expr::Add(a, b) => eval(a, main, fixed) + eval(b, main, fixed),
    Expr::Sub(a, b) => eval(a, main, fixed) - eval(b, main, fixed),
    Expr::Mul(a, b) => eval(a, main, fixed) * eval(b, main, fixed),
    Expr::Neg(a) => -eval(a, main, fixed),
    _ => unreachable!(),
  }
}

/// Native check of every constraint and of the exact LogUp multiset balance
/// (tuples compared after trimming trailing zeros, as the fingerprint does).
fn native_check(
  inputs: &[CircuitInputs<Scalar>],
  shared: &[Option<usize>],
  traces: &[RowMajorMatrix<Scalar>],
  claims: &[Vec<Scalar>],
) -> Result<(), String> {
  let mut balance: HashMap<Vec<Scalar>, Scalar> = HashMap::new();
  let trim = |mut v: Vec<Scalar>| {
    while v.last() == Some(&Scalar::ZERO) {
      v.pop();
    }
    v
  };
  for c in claims {
    *balance.entry(trim(c.clone())).or_insert(Scalar::ZERO) += Scalar::ONE;
  }
  for (ci, (input, trace)) in inputs.iter().zip(traces).enumerate() {
    let fixed = inputs[shared[ci].unwrap_or(ci)].preprocessed.as_ref().unwrap();
    for r in 0..trace.height() {
      let main = &trace.values[r * trace.width..(r + 1) * trace.width];
      let fx = &fixed.values[r * fixed.width..(r + 1) * fixed.width];
      for (k, c) in input.constraints.iter().enumerate() {
        if eval(c, main, fx) != Scalar::ZERO {
          return Err(format!("circuit {ci} row {r} constraint {k}"));
        }
      }
      for l in &input.lookups {
        let m = eval(&l.multiplicity, main, fx);
        if m != Scalar::ZERO {
          let t = trim(l.args.iter().map(|a| eval(a, main, fx)).collect());
          *balance.entry(t).or_insert(Scalar::ZERO) += m;
        }
      }
    }
  }
  match balance.iter().find(|(_, m)| **m != Scalar::ZERO) {
    Some((t, m)) => {
      Err(format!("unbalanced tuple {:?} by {m:?}", &t[..t.len().min(3)]))
    },
    None => Ok(()),
  }
}

struct Setup {
  inputs: Vec<CircuitInputs<Scalar>>,
  shared: Vec<Option<usize>>,
  system: System<KzgConfig>,
  key: multi_stark::system::ProverKey<KzgConfig>,
}

fn setup(backend: &Backend<'_, '_, '_>) -> Setup {
  let (inputs, shared) = backend.circuit_inputs();
  let max = inputs
    .iter()
    .filter_map(|i| i.preprocessed.as_ref())
    .map(|m| m.height())
    .max()
    .unwrap();
  let srs = Arc::new(Srs::unsafe_dev_setup(4 * max, b"aiur-template-v2-test"));
  let (system, key) =
    system_with_slots(KzgConfig::new(srs, 8), inputs.clone(), &shared, true)
      .unwrap();
  assert_eq!(
    fixed_slots(&system),
    1 + backend.stacked().len(),
    "one shared narrow matrix, one per stacked table"
  );
  Setup { inputs, shared, system, key }
}

fn accepts(
  s: &Setup,
  traces: Vec<RowMajorMatrix<Scalar>>,
  claims: &[Vec<Scalar>],
) -> bool {
  let refs: Vec<&[Scalar]> = claims.iter().map(Vec::as_slice).collect();
  let witness = SystemWitness::from_stage_1(traces, &s.system);
  let proof = s.system.prove_multiple_claims(&s.key, &refs, witness);
  s.system.verify_multiple_claims(&refs, &proof).is_ok()
}

fn rejects(
  s: &Setup,
  traces: Vec<RowMajorMatrix<Scalar>>,
  claims: &[Vec<Scalar>],
  what: &str,
) {
  let native = native_check(&s.inputs, &s.shared, &traces, claims);
  assert!(native.is_err(), "{what}: native check accepted");
  assert!(!accepts(s, traces, claims), "{what}: KZG verifier accepted");
  eprintln!("{what}: rejected ({})", native.unwrap_err());
}

fn slot_value(
  b: &Backend<'_, '_, '_>,
  traces: &[RowMajorMatrix<Scalar>],
  fi: usize,
  n: usize,
  slot: u32,
) -> Scalar {
  let w = b.config.width;
  let (s, r, c) = b.cells_of(fi, n, slot)[0];
  traces[s].values[r * w + c]
}

fn set_slot(
  b: &Backend<'_, '_, '_>,
  traces: &mut [RowMajorMatrix<Scalar>],
  fi: usize,
  n: usize,
  slot: u32,
  v: Scalar,
) {
  let w = b.config.width;
  for (s, r, c) in b.cells_of(fi, n, slot) {
    traces[s].values[r * w + c] = v;
  }
}

/// Every instance's column cells reproduce the compiler's wide row.
fn reconstructs(
  b: &Backend<'_, '_, '_>,
  wide: &[RowMajorMatrix<Scalar>],
  raw: &[usize],
  traces: &[RowMajorMatrix<Scalar>],
) {
  for (fi, t) in b.templates.iter().enumerate() {
    if Some(fi) == b.compress_circuit() {
      continue;
    }
    for n in 0..raw[fi] {
      for (s, d) in t.slots.iter().enumerate() {
        if let SlotDef::Column { col, .. } = d {
          assert_eq!(
            slot_value(b, traces, fi, n, u32::try_from(s).unwrap()),
            wide[fi].values[n * wide[fi].width + col]
          );
        }
      }
    }
  }
}

/// Honest witnesses for `inputs` satisfy every constraint natively,
/// reproduce the wide rows, and prove and verify; a changed output claim
/// is rejected.
fn honest_proofs(shards: usize, inputs: &[(u64, Scalar)]) {
  let plan = plan();
  let compiler = Compiler::with_lookup_budget(&plan, Some(4)).unwrap();
  for &(n, x) in inputs {
    let args = [f(n), x];
    let record = plan.program().execute(ENTRY, args.to_vec()).unwrap();
    let public = plan.public_args(&record, ENTRY, &args).unwrap();
    let claim = plan.public_claim(ENTRY, &public, &record.output).unwrap();
    let backend =
      Backend::new(&compiler, &plan, config(&compiler, &record, shards, true))
        .unwrap();
    assert_eq!(backend.shards, shards);
    if n == 3 {
      for (t, name) in backend.templates.iter().zip(compiler.names()) {
        eprintln!(
          "{name}: rows {} slots {} messages {} {:?}",
          t.rows.len(),
          t.slots.len(),
          t.messages.len(),
          t.stats
        );
      }
      for c in backend.counts() {
        eprintln!("{c:?}");
      }
    }
    let (traces, key) = backend.witness(&record, ENTRY, &args).unwrap();
    let claims = backend.claims(&claim, key);
    let s = setup(&backend);
    native_check(&s.inputs, &s.shared, &traces, &claims).unwrap();
    let wide = compiler.generate(&record, ENTRY, &args).unwrap();
    reconstructs(
      &backend,
      &wide,
      &compiler.raw_row_counts(&record).unwrap(),
      &traces,
    );
    assert!(accepts(&s, traces.clone(), &claims), "honest n={n}");
    let mut wrong = claims.clone();
    *wrong.last_mut().unwrap().last_mut().unwrap() += Scalar::ONE;
    assert!(!accepts(&s, traces, &wrong), "changed output accepted");
  }
}

