//! Second narrow template layout (periodic shards sharing one fixed matrix,
//! degree-3 spans, lane-slot messages) on the BN254 trace fixture: honest
//! proofs, and forged witnesses the KZG verifier must reject. Forgeries
//! across shards are also run against a variant without per-shard offsets,
//! which accepts them.
//!
//! One shard is the L3 narrow stage's configuration: it shares no fixed
//! slot, so the pinned upstream multi-stark builds it and its tests run by
//! default. Two shards share one fixed slot through `System::new_shared`,
//! which exists only in the multi-stark fork; those tests are compiled with
//! the `shared-fixed` feature only:
//!
//!   tools/cargo-shared-fixed.sh test -p ix-proof-compression --release --test aiur_template_v2
//!
//! The program is `crates/aiur/tests/fixtures/bn254-trace.ixa` (about 1 KB),
//! regenerated by `lake env lean --run Scripts/CheckAiurCompressionFixtures.lean --update`.

