/// Forgeries within one shard: a wired cell, a spare instance and the
/// stacked map and ROM tables.
fn local_forgeries(
  backend: &Backend<'_, '_, '_>,
  s: &Setup,
  honest: &[RowMajorMatrix<Scalar>],
  claims: &[Vec<Scalar>],
  raw: &[usize],
) {
  let w = backend.config.width;
  // Altered wired cell (a non-first cell of a multi-cell slot).
  let (fi, n, slot) = (0..backend.templates.len())
    .flat_map(|fi| (0..raw[fi]).map(move |n| (fi, n)))
    .find_map(|(fi, n)| {
      let t = &backend.templates[fi];
      (0..u32::try_from(t.slots.len()).unwrap())
        .find(|&s| t.occurrences[s as usize] > 1)
        .map(|s| (fi, n, s))
    })
    .unwrap();
  let mut tr = honest.to_vec();
  let (sh, r, c) = backend.cells_of(fi, n, slot)[1];
  tr[sh].values[r * w + c] += Scalar::ONE;
  rejects(s, tr, claims, "altered wired value");

  // A spare instance receiving a real tuple.
  let fi = (0..backend.templates.len())
    .find(|&fi| {
      raw[fi] >= 1 && backend.templates[fi].messages[0].mult.is_some()
    })
    .unwrap();
  let recv = backend.templates[fi].messages[0].clone();
  let spare = raw[fi];
  let mut tr = honest.to_vec();
  for &p in &recv.payload {
    let v = slot_value(backend, honest, fi, 0, p);
    set_slot(backend, &mut tr, fi, spare, p, v);
  }
  set_slot(backend, &mut tr, fi, spare, recv.mult.unwrap(), recv.mc.inverse());
  rejects(s, tr, claims, "spare instance carrying a message");

  // Stacked map table: a used row's count raised.
  let tables = backend.stacked();
  let at = |k: usize| backend.shards + k;
  let k = tables
    .iter()
    .position(|t| matches!(t.source, TableSource::Map(_)))
    .expect("a map table");
  let r = (0..tables[k].rows)
    .find(|&r| honest[at(k)].values[r] != Scalar::ZERO)
    .expect("a used map row");
  let mut tr = honest.to_vec();
  tr[at(k)].values[r] += Scalar::ONE;
  rejects(s, tr, claims, "map table count raised");

  // Stacked ROM table: a word of a read address changed (the words are
  // witness values; the address is the fixed key).
  let k = tables
    .iter()
    .position(|t| matches!(t.source, TableSource::Rom(_)))
    .expect("a ROM table");
  let mw = tables[k].main_width;
  let r = (0..tables[k].rows)
    .find(|&r| honest[at(k)].values[r * mw] != Scalar::ZERO)
    .expect("a read address");
  let mut tr = honest.to_vec();
  tr[at(k)].values[r * mw + 1] += Scalar::ONE;
  rejects(s, tr, claims, "ROM word changed");

  // Stacked ROM table: a read moved to a padding row past the capacity,
  // whose `sel` is 0.
  let t = &tables[k];
  if t.height() > t.rows {
    let mut tr = honest.to_vec();
    let row: Vec<Scalar> = tr[at(k)].values[r * mw..(r + 1) * mw].to_vec();
    tr[at(k)].values[t.rows * mw..(t.rows + 1) * mw].copy_from_slice(&row);
    tr[at(k)].values[r * mw] = Scalar::ZERO;
    rejects(s, tr, claims, "ROM read moved to a padding row");
  }
}

