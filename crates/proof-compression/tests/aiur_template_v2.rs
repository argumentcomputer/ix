/// The layout this backend derives, in the Lean v2 export format, is
/// adopted; a changed template, label stride or bus code is refused; and the
/// adopted fixed matrix proves the honest witness.
fn lean_export_round_trip(shards: usize) {
  let plan = plan();
  let compiler = Compiler::with_lookup_budget(&plan, Some(4)).unwrap();
  let args = [f(3), -Scalar::ONE];
  let record = plan.program().execute(ENTRY, args.to_vec()).unwrap();
  let public = plan.public_args(&record, ENTRY, &args).unwrap();
  let claim = plan.public_claim(ENTRY, &public, &record.output).unwrap();
  let make = || {
    Backend::new(&compiler, &plan, config(&compiler, &record, shards, true))
      .unwrap()
  };
  let reference = make().lean_reference().unwrap();
  let input = lean::input2(
    &compiler,
    &plan,
    &make().config,
    std::path::Path::new(FIXTURE),
    "",
  )
  .unwrap();
  assert_eq!(
    input["circuits"].as_array().unwrap().len(),
    compiler.function_circuits()
  );
  let dir = std::env::temp_dir()
    .join(format!("ix-v2-lean-{shards}-{}", std::process::id()));
  std::fs::create_dir_all(&dir).unwrap();
  let (json, bin) = (dir.join("t.layout2.json"), dir.join("t.fixed2.bin"));
  std::fs::write(&json, serde_json::to_vec(&reference.out).unwrap()).unwrap();
  lean::write_fixed(
    &bin,
    reference.fixed_rows,
    reference.fixed_width,
    &reference.fixed,
  )
  .unwrap();
  let load = || lean::Layout::load(&json, &bin).unwrap();

  let mut tampered = load();
  tampered.out["labels_per_shard"] =
    serde_json::json!(tampered.out["labels_per_shard"].as_u64().unwrap() - 1);
  assert!(make().adopt_lean(tampered).is_err(), "changed label stride");
  let mut tampered = load();
  tampered.out["templates"][0]["rows"][0] = serde_json::json!("empty");
  assert!(make().adopt_lean(tampered).is_err(), "changed template row");
  let mut tampered = load();
  tampered.out["buses"][0][2] = serde_json::json!("7");
  assert!(make().adopt_lean(tampered).is_err(), "changed bus code");

  let mut tampered = load();
  tampered.out["buses"][0][3] =
    serde_json::json!(!tampered.out["buses"][0][3].as_bool().unwrap());
  assert!(make().adopt_lean(tampered).is_err(), "changed bus lane flag");
  let mut tampered = load();
  let rom = tampered.out["tables"]
    .as_array()
    .unwrap()
    .iter()
    .position(|t| t["tag"] == "2")
    .unwrap();
  tampered.out["tables"][rom]["rows"] = serde_json::json!(
    tampered.out["tables"][rom]["rows"].as_u64().unwrap() + 1
  );
  assert!(
    make().adopt_lean(tampered).unwrap_err().contains("stacked tables"),
    "changed ROM capacity"
  );
  let mut tampered = load();
  tampered.out["tables"][0]["key_base"] = serde_json::json!(0);
  assert!(
    make().adopt_lean(tampered).unwrap_err().contains("stacked tables"),
    "changed map key base"
  );

  let mut backend = make();
  backend.adopt_lean(load()).unwrap();
  std::fs::remove_dir_all(&dir).unwrap();
  let (traces, key) = backend.witness(&record, ENTRY, &args).unwrap();
  assert_eq!(key, Scalar::ZERO, "the root invocation has id 0");
  let claims = backend.claims(&claim, key);
  backend.check_lean_request(&claims).unwrap();
  let s = setup(&backend);
  assert!(
    accepts(&s, traces, &claims),
    "honest witness under the adopted fixed matrix"
  );
}

