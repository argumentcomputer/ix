//! The generated sources of the formal programs, which `lake build ix`
//! writes before Cargo compiles them (`crates/formal-generated`). Relative
//! to the generated directory:
//!
//! - `native/<name>.rs`: the native executor, from the bytecode and its
//!   execution plan ([`aiur_codegen::native_executor`]);
//! - `cuda/<name>/`, for CUDA builds only: the compiled trace writers, from
//!   the population plans and placement ([`aiur_tracegen::bundle::sources`]).
//!
//! A native executor's header records only its fingerprint, so a change
//! that leaves the bytecode and execution plan alone, such as regrouping
//! circuits, leaves the file byte-identical and Cargo does not recompile
//! it. The trace writers depend on the grouping and also record the digest
//! of the package they were generated from.
use crate::system::Program;

/// The formal programs: the name their sources are filed under, and the
/// type name of their native executor.
pub const PROGRAMS: [(&str, &str); 3] =
  [("ixvm", "Ixvm"), ("verifier", "Verifier"), ("aggregation", "Aggregation")];

fn hex(bytes: &[u8]) -> String {
  bytes.iter().map(|b| format!("{b:02x}")).collect()
}

/// The generated files of the formal program `name`, as (path, contents)
/// pairs relative to the generated directory: the native executor, and with
/// `cuda` the trace writers.
pub fn sources(
  program: &Program,
  name: &str,
  cuda: bool,
) -> Result<Vec<(String, String)>, String> {
  let (_, executor) = PROGRAMS
    .iter()
    .find(|(n, _)| *n == name)
    .ok_or_else(|| format!("{name} is not a formal program"))?;
  let notice = format!(
    "// @generated by `lake build ix` from the {name} program; do not edit.\n"
  );
  let native = aiur_codegen::native_executor(program.checked(), executor)?;
  let mut files =
    vec![(format!("native/{name}.rs"), format!("{notice}{native}"))];
  if cuda {
    let described =
      aiur_tracegen::describe(program.checked(), program.trace().clone())?;
    let preamble =
      format!("{notice}// Package digest {}.\n", hex(program.identity()));
    for (file, contents) in
      aiur_tracegen::bundle::sources(&described, name, &preamble)?
    {
      files.push((format!("cuda/{name}/{file}"), contents));
    }
  }
  Ok(files)
}
