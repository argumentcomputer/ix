/// Lean's own recursor families round-trip: compiled as given, the
/// decompiled environment is the source, recursors and support
/// declarations included.
#[test]
fn source_recursors_decompile_to_the_source() {
  use crate::compile::env::compile_env;
  use crate::decompile::{check_decompile, decompile_env};
  use std::sync::Arc;

  let (flat, _, _) = build_alpha_collapse_env_with_recursors();
  let (nested, _) = build_nested_source_recursors();
  for mut source in [flat, nested] {
    add_support_declarations(&mut source);
    let source = Arc::new(source);
    let stt = compile_env(&source).unwrap();
    assert!(stt.ungrounded.is_empty(), "{:?}", stt.ungrounded);
    let dstt = decompile_env(&stt).unwrap();
    let check = check_decompile(&source, &stt, &dstt).unwrap();
    assert_eq!(check.failures(|_| false), 0, "{check:?}");
    assert_eq!(check.matches, source.len());
  }
}
