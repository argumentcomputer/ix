//! Lean's own recursor families through the kernel's direct ingress and
//! through compilation: hand-transcribed Lean fixtures, checked as given.

use bignat::Nat;
use ix_common::env::{
  BinderInfo, ConstantInfo, ConstantVal, ConstructorVal, Env as LeanEnv,
  Expr as LeanExpr, InductiveVal, Level, Name, RecursorRule, RecursorVal,
};

fn n(s: &str) -> Name {
  Name::str(Name::anon(), s.to_string())
}

/// Helper: `∀ (name : domain), body` with default binder info.
fn epi(name: Name, domain: LeanExpr, body: LeanExpr) -> LeanExpr {
  LeanExpr::all(name, domain, body, BinderInfo::Default)
}

/// Build a minimal Prop mutual block: A | a : B → A, B | b : A → B.
///
/// Both A and B are in Prop (Sort 0), with single constructors that
/// cross-reference the sibling. `all = [A, B]` on both inductives.
/// No recursors.
fn build_alpha_collapse_env() -> (LeanEnv, Name, Name) {
  build_alpha_collapse_env_named(n("A"), n("B"))
}

fn build_alpha_collapse_env_named(a: Name, b: Name) -> (LeanEnv, Name, Name) {
  let hyg = Name::num(
    Name::str(Name::anon(), "a._@._internal._hyg".into()),
    Nat::from(0u64),
  );
  let a_ctor = Name::str(a.clone(), "a".into());
  let b_ctor = Name::str(b.clone(), "b".into());
  let all = vec![a.clone(), b.clone()];
  let a_c = LeanExpr::cnst(a.clone(), vec![]);
  let b_c = LeanExpr::cnst(b.clone(), vec![]);
  let prop = LeanExpr::sort(Level::zero());

  let mut env = LeanEnv::default();
  env.insert(
    a.clone(),
    ConstantInfo::InductInfo(InductiveVal {
      cnst: ConstantVal {
        name: a.clone(),
        level_params: vec![],
        typ: prop.clone(),
      },
      num_params: Nat::from(0u64),
      num_indices: Nat::from(0u64),
      all: all.clone(),
      ctors: vec![a_ctor.clone()],
      num_nested: Nat::from(0u64),
      is_rec: true,
      is_unsafe: false,
      is_reflexive: false,
    }),
  );
  env.insert(
    b.clone(),
    ConstantInfo::InductInfo(InductiveVal {
      cnst: ConstantVal {
        name: b.clone(),
        level_params: vec![],
        typ: prop.clone(),
      },
      num_params: Nat::from(0u64),
      num_indices: Nat::from(0u64),
      all: all.clone(),
      ctors: vec![b_ctor.clone()],
      num_nested: Nat::from(0u64),
      is_rec: true,
      is_unsafe: false,
      is_reflexive: false,
    }),
  );
  // A.a : B → A
  env.insert(
    a_ctor.clone(),
    ConstantInfo::CtorInfo(ConstructorVal {
      cnst: ConstantVal {
        name: a_ctor,
        level_params: vec![],
        typ: epi(hyg.clone(), b_c, a_c.clone()),
      },
      induct: a.clone(),
      cidx: Nat::from(0u64),
      num_params: Nat::from(0u64),
      num_fields: Nat::from(1u64),
      is_unsafe: false,
    }),
  );
  // B.b : A → B
  env.insert(
    b_ctor.clone(),
    ConstantInfo::CtorInfo(ConstructorVal {
      cnst: ConstantVal {
        name: b_ctor,
        level_params: vec![],
        typ: epi(hyg, a_c, LeanExpr::cnst(b.clone(), vec![])),
      },
      induct: b.clone(),
      cidx: Nat::from(0u64),
      num_params: Nat::from(0u64),
      num_fields: Nat::from(1u64),
      is_unsafe: false,
    }),
  );
  (env, a, b)
}

/// The uncollapsed recursors Lean generates for the Prop A/B fixture.
/// Transcribed from Lean 4.33.1's `#print A.rec` / `#print B.rec`, not
/// generated by the compiler under test. Both have two dependent Prop
/// motives, two minors, and a rule recursively calling the sibling recursor.
fn build_alpha_collapse_env_with_recursors() -> (LeanEnv, Name, Name) {
  build_alpha_collapse_env_with_recursors_named(n("A"), n("B"))
}

fn build_alpha_collapse_env_with_recursors_named(
  a: Name,
  b: Name,
) -> (LeanEnv, Name, Name) {
  let (mut env, a, b) = build_alpha_collapse_env_named(a, b);
  let a_ctor = Name::str(a.clone(), "a".into());
  let b_ctor = Name::str(b.clone(), "b".into());
  let a_rec = Name::str(a.clone(), "rec".into());
  let b_rec = Name::str(b.clone(), "rec".into());
  let a_c = LeanExpr::cnst(a.clone(), vec![]);
  let b_c = LeanExpr::cnst(b.clone(), vec![]);
  insert_two_motive_recursors(
    &mut env,
    &[a.clone(), b.clone()],
    [a_rec, b_rec],
    [a_c, b_c],
    [
      (a_ctor.clone(), LeanExpr::cnst(a_ctor, vec![])),
      (b_ctor.clone(), LeanExpr::cnst(b_ctor, vec![])),
    ],
    &[],
  );
  (env, a, b)
}

/// Shared binder/rule shape of the Lean-transcribed A/B and Tree/Wrap Tree
/// fixtures. `ctor_apps` includes specialized parameters (Wrap.mk Tree).
fn insert_two_motive_recursors(
  env: &mut LeanEnv,
  all: &[Name],
  rec_names: [Name; 2],
  major_types: [LeanExpr; 2],
  ctor_apps: [(Name, LeanExpr); 2],
  level_params: &[Name],
) {
  let [a_rec, b_rec] = rec_names;
  let [a_c, b_c] = major_types;
  let [(a_ctor, a_ctor_app), (b_ctor, b_ctor_app)] = ctor_apps;
  let elim_level =
    level_params.first().map_or_else(Level::zero, |u| Level::param(u.clone()));
  let motive_sort = LeanExpr::sort(elim_level);
  let rec_us: Vec<_> = level_params.iter().cloned().map(Level::param).collect();
  let bv = |i: u64| LeanExpr::bvar(Nat::from(i));

  // Domains are scoped under the preceding prefix binders:
  // {mA : A → Sort u} {mB : B → Sort u} (u = 0 for the Prop fixture)
  // (a : ∀ x : B, mB x → mA (A.a x))
  // (b : ∀ x : A, mA x → mB (B.b x)).
  let prefix = [
    (
      n("motive_1"),
      epi(n("t"), a_c.clone(), motive_sort.clone()),
      BinderInfo::Implicit,
    ),
    (
      n("motive_2"),
      epi(n("t"), b_c.clone(), motive_sort),
      BinderInfo::Implicit,
    ),
    (
      n("a"),
      epi(
        n("x"),
        b_c.clone(),
        epi(
          n("ih"),
          LeanExpr::app(bv(1), bv(0)),
          LeanExpr::app(bv(3), LeanExpr::app(a_ctor_app, bv(1))),
        ),
      ),
      BinderInfo::Default,
    ),
    (
      n("b"),
      epi(
        n("x"),
        a_c.clone(),
        epi(
          n("ih"),
          LeanExpr::app(bv(3), bv(0)),
          LeanExpr::app(bv(3), LeanExpr::app(b_ctor_app, bv(1))),
        ),
      ),
      BinderInfo::Default,
    ),
  ];

  for (rec_name, ctor, major_ty, field_ty, motive_idx, minor_idx, peer) in [
    (&a_rec, &a_ctor, &a_c, &b_c, 4, 2, &b_rec),
    (&b_rec, &b_ctor, &b_c, &a_c, 3, 1, &a_rec),
  ] {
    let typ = prefix.iter().rev().fold(
      epi(n("t"), major_ty.clone(), LeanExpr::app(bv(motive_idx), bv(0))),
      |body, (name, domain, info)| {
        LeanExpr::all(name.clone(), domain.clone(), body, info.clone())
      },
    );
    // λ mA mB a b x, minor x (peer.rec mA mB a b x).
    let recursive_call = (0..=4)
      .rev()
      .fold(LeanExpr::cnst(peer.clone(), rec_us.clone()), |f, i| {
        LeanExpr::app(f, bv(i))
      });
    let rhs = LeanExpr::lam(
      n("x"),
      field_ty.clone(),
      LeanExpr::app(LeanExpr::app(bv(minor_idx), bv(0)), recursive_call),
      BinderInfo::Default,
    );
    let rhs = prefix.iter().rev().fold(rhs, |body, (name, domain, _)| {
      LeanExpr::lam(name.clone(), domain.clone(), body, BinderInfo::Default)
    });
    env.insert(
      rec_name.clone(),
      ConstantInfo::RecInfo(RecursorVal {
        cnst: ConstantVal {
          name: rec_name.clone(),
          level_params: level_params.to_vec(),
          typ,
        },
        all: all.to_vec(),
        num_params: Nat::from(0u64),
        num_indices: Nat::from(0u64),
        num_motives: Nat::from(2u64),
        num_minors: Nat::from(2u64),
        rules: vec![RecursorRule {
          ctor: ctor.clone(),
          n_fields: Nat::from(1u64),
          rhs,
        }],
        k: false,
        is_unsafe: false,
      }),
    );
  }
}

/// Lean 4.33.1: Wrap (α : Type) | mk : α → Wrap α;
/// Tree | node : Wrap Tree → Tree. The nested source peers are
/// Tree.rec, Tree.rec_1, both universe-polymorphic with two motives/minors.
fn build_nested_source_recursors() -> (LeanEnv, Name) {
  let mut env = LeanEnv::default();
  let wrap = n("Wrap");
  let tree = n("Tree");
  let wrap_mk = Name::str(wrap.clone(), "mk".into());
  let node = Name::str(tree.clone(), "node".into());
  let tree_c = LeanExpr::cnst(tree.clone(), vec![]);
  let wrap_c = LeanExpr::cnst(wrap.clone(), vec![]);
  let wrap_tree = LeanExpr::app(wrap_c.clone(), tree_c.clone());
  let type0 = LeanExpr::sort(Level::succ(Level::zero()));
  for (name, typ, ctor, params, nested) in [
    (&wrap, epi(n("α"), type0.clone(), type0.clone()), &wrap_mk, 1u64, 0u64),
    (&tree, type0.clone(), &node, 0, 1),
  ] {
    env.insert(
      name.clone(),
      ConstantInfo::InductInfo(InductiveVal {
        cnst: ConstantVal { name: name.clone(), level_params: vec![], typ },
        num_params: Nat::from(params),
        num_indices: Nat::from(0u64),
        all: vec![name.clone()],
        ctors: vec![ctor.clone()],
        num_nested: Nat::from(nested),
        is_rec: nested != 0,
        is_unsafe: false,
        is_reflexive: false,
      }),
    );
  }
  let wrap_mk_ty = LeanExpr::all(
    n("α"),
    type0,
    epi(
      n("x"),
      LeanExpr::bvar(Nat::from(0u64)),
      LeanExpr::app(wrap_c, LeanExpr::bvar(Nat::from(1u64))),
    ),
    BinderInfo::Implicit,
  );
  for (name, typ, induct, params) in [
    (&wrap_mk, wrap_mk_ty, &wrap, 1u64),
    (&node, epi(n("x"), wrap_tree.clone(), tree_c.clone()), &tree, 0),
  ] {
    env.insert(
      name.clone(),
      ConstantInfo::CtorInfo(ConstructorVal {
        cnst: ConstantVal { name: name.clone(), level_params: vec![], typ },
        induct: induct.clone(),
        cidx: Nat::from(0u64),
        num_params: Nat::from(params),
        num_fields: Nat::from(1u64),
        is_unsafe: false,
      }),
    );
  }
  insert_two_motive_recursors(
    &mut env,
    std::slice::from_ref(&tree),
    [
      Name::str(tree.clone(), "rec".into()),
      Name::str(tree.clone(), "rec_1".into()),
    ],
    [tree_c.clone(), wrap_tree],
    [
      (node.clone(), LeanExpr::cnst(node, vec![])),
      (wrap_mk.clone(), LeanExpr::app(LeanExpr::cnst(wrap_mk, vec![]), tree_c)),
    ],
    &[n("u")],
  );
  (env, tree)
}

/// Build a simple Type-level inductive (Nat-like): T | Z : T | S : T → T
fn build_type_nat_env() -> (LeanEnv, Name) {
  let _u = Name::str(Name::anon(), "u".to_string());
  let t = n("T");
  let z_ctor = Name::str(t.clone(), "Z".into());
  let s_ctor = Name::str(t.clone(), "S".into());
  let t_c = LeanExpr::cnst(t.clone(), vec![]);
  let type0 = LeanExpr::sort(Level::succ(Level::zero()));
  let hyg = Name::num(
    Name::str(Name::anon(), "a._@._internal._hyg".into()),
    Nat::from(0u64),
  );

  let mut env = LeanEnv::default();
  env.insert(
    t.clone(),
    ConstantInfo::InductInfo(InductiveVal {
      cnst: ConstantVal { name: t.clone(), level_params: vec![], typ: type0 },
      num_params: Nat::from(0u64),
      num_indices: Nat::from(0u64),
      all: vec![t.clone()],
      ctors: vec![z_ctor.clone(), s_ctor.clone()],
      num_nested: Nat::from(0u64),
      is_rec: true,
      is_unsafe: false,
      is_reflexive: false,
    }),
  );
  // T.Z : T
  env.insert(
    z_ctor.clone(),
    ConstantInfo::CtorInfo(ConstructorVal {
      cnst: ConstantVal {
        name: z_ctor,
        level_params: vec![],
        typ: t_c.clone(),
      },
      induct: t.clone(),
      cidx: Nat::from(0u64),
      num_params: Nat::from(0u64),
      num_fields: Nat::from(0u64),
      is_unsafe: false,
    }),
  );
  // T.S : T → T
  env.insert(
    s_ctor.clone(),
    ConstantInfo::CtorInfo(ConstructorVal {
      cnst: ConstantVal {
        name: s_ctor,
        level_params: vec![],
        typ: epi(hyg, t_c.clone(), t_c),
      },
      induct: t.clone(),
      cidx: Nat::from(1u64),
      num_params: Nat::from(0u64),
      num_fields: Nat::from(1u64),
      is_unsafe: false,
    }),
  );
  // PUnit and PProd, the support declarations of Lean's `.below`.
  add_punit_pprod(&mut env);
  (env, t)
}

/// Add minimal PUnit.{u} and PProd.{u,v} definitions to a test environment.
fn add_punit_pprod(env: &mut LeanEnv) {
  let u_name = n("u");
  let v_name = n("v");
  let sort_u = LeanExpr::sort(Level::param(u_name.clone()));
  let sort_v = LeanExpr::sort(Level::param(v_name.clone()));

  // PUnit.{u} : Sort u, with one constructor PUnit.unit.{u} : PUnit.{u}
  let punit = n("PUnit");
  let punit_unit = Name::str(punit.clone(), "unit".into());
  let punit_ty = sort_u.clone(); // PUnit : Sort u
  let punit_c =
    LeanExpr::cnst(punit.clone(), vec![Level::param(u_name.clone())]);
  env.insert(
    punit.clone(),
    ConstantInfo::InductInfo(InductiveVal {
      cnst: ConstantVal {
        name: punit.clone(),
        level_params: vec![u_name.clone()],
        typ: punit_ty,
      },
      num_params: Nat::from(0u64),
      num_indices: Nat::from(0u64),
      all: vec![punit.clone()],
      ctors: vec![punit_unit.clone()],
      num_nested: Nat::from(0u64),
      is_rec: false,
      is_unsafe: false,
      is_reflexive: false,
    }),
  );
  env.insert(
    punit_unit.clone(),
    ConstantInfo::CtorInfo(ConstructorVal {
      cnst: ConstantVal {
        name: punit_unit,
        level_params: vec![u_name.clone()],
        typ: punit_c,
      },
      induct: punit.clone(),
      cidx: Nat::from(0u64),
      num_params: Nat::from(0u64),
      num_fields: Nat::from(0u64),
      is_unsafe: false,
    }),
  );

  // PProd.{u, v} : Sort u → Sort v → Sort (max 1 u v)
  let pprod = n("PProd");
  let pprod_mk = Name::str(pprod.clone(), "mk".into());
  let max_1_u_v = Level::max(
    Level::succ(Level::zero()),
    Level::max(Level::param(u_name.clone()), Level::param(v_name.clone())),
  );
  // Type: ∀ (α : Sort u) (β : Sort v), Sort (max 1 u v)
  let pprod_ty = LeanExpr::all(
    Name::str(Name::anon(), "α".into()),
    sort_u.clone(),
    LeanExpr::all(
      Name::str(Name::anon(), "β".into()),
      sort_v.clone(),
      LeanExpr::sort(max_1_u_v),
      BinderInfo::Default,
    ),
    BinderInfo::Default,
  );
  // mk : ∀ {α : Sort u} {β : Sort v}, α → β → PProd α β
  let pprod_c = LeanExpr::cnst(
    pprod.clone(),
    vec![Level::param(u_name.clone()), Level::param(v_name.clone())],
  );
  let mk_ty = LeanExpr::all(
    Name::str(Name::anon(), "α".into()),
    sort_u,
    LeanExpr::all(
      Name::str(Name::anon(), "β".into()),
      sort_v,
      LeanExpr::all(
        Name::str(Name::anon(), "fst".into()),
        LeanExpr::bvar(Nat::from(1u64)),
        LeanExpr::all(
          Name::str(Name::anon(), "snd".into()),
          LeanExpr::bvar(Nat::from(1u64)),
          LeanExpr::app(
            LeanExpr::app(pprod_c, LeanExpr::bvar(Nat::from(3u64))),
            LeanExpr::bvar(Nat::from(2u64)),
          ),
          BinderInfo::Default,
        ),
        BinderInfo::Default,
      ),
      BinderInfo::Implicit,
    ),
    BinderInfo::Implicit,
  );
  env.insert(
    pprod.clone(),
    ConstantInfo::InductInfo(InductiveVal {
      cnst: ConstantVal {
        name: pprod.clone(),
        level_params: vec![u_name.clone(), v_name.clone()],
        typ: pprod_ty,
      },
      num_params: Nat::from(2u64),
      num_indices: Nat::from(0u64),
      all: vec![pprod.clone()],
      ctors: vec![pprod_mk.clone()],
      num_nested: Nat::from(0u64),
      is_rec: false,
      is_unsafe: false,
      is_reflexive: false,
    }),
  );
  env.insert(
    pprod_mk.clone(),
    ConstantInfo::CtorInfo(ConstructorVal {
      cnst: ConstantVal {
        name: pprod_mk,
        level_params: vec![u_name, v_name],
        typ: mk_ty,
      },
      induct: pprod,
      cidx: Nat::from(0u64),
      num_params: Nat::from(2u64),
      num_fields: Nat::from(2u64),
      is_unsafe: false,
    }),
  );
}

/// Support declarations for compile_env fixtures (PUnit, PProd, And, True):
/// valid source declarations, not generated placeholders or trusted kernel
/// entries.
fn add_support_declarations(env: &mut LeanEnv) {
  add_punit_pprod(env);
  let prop = LeanExpr::sort(Level::zero());
  let and = n("And");
  let intro = Name::str(and.clone(), "intro".into());
  let bv = |i: u64| LeanExpr::bvar(Nat::from(i));
  let and_ty =
    epi(n("a"), prop.clone(), epi(n("b"), prop.clone(), prop.clone()));
  let intro_ty = LeanExpr::all(
    n("a"),
    prop.clone(),
    LeanExpr::all(
      n("b"),
      prop.clone(),
      epi(
        n("left"),
        bv(1),
        epi(
          n("right"),
          bv(1),
          LeanExpr::app(
            LeanExpr::app(LeanExpr::cnst(and.clone(), vec![]), bv(3)),
            bv(2),
          ),
        ),
      ),
      BinderInfo::Implicit,
    ),
    BinderInfo::Implicit,
  );
  for (name, ctor, typ, ctor_typ, params, fields) in [
    (and, intro, and_ty, intro_ty, 2u64, 2u64),
    (
      n("True"),
      Name::str(n("True"), "intro".into()),
      prop,
      LeanExpr::cnst(n("True"), vec![]),
      0,
      0,
    ),
  ] {
    env.insert(
      name.clone(),
      ConstantInfo::InductInfo(InductiveVal {
        cnst: ConstantVal { name: name.clone(), level_params: vec![], typ },
        num_params: Nat::from(params),
        num_indices: Nat::from(0u64),
        all: vec![name.clone()],
        ctors: vec![ctor.clone()],
        num_nested: Nat::from(0u64),
        is_rec: false,
        is_unsafe: false,
        is_reflexive: false,
      }),
    );
    env.insert(
      ctor.clone(),
      ConstantInfo::CtorInfo(ConstructorVal {
        cnst: ConstantVal { name: ctor, level_params: vec![], typ: ctor_typ },
        induct: name,
        cidx: Nat::from(0u64),
        num_params: Nat::from(params),
        num_fields: Nat::from(fields),
        is_unsafe: false,
      }),
    );
  }
}

fn assert_source_recursors_check(
  source: &LeanEnv,
  head: &Name,
  expected_peers: &[Name],
) {
  use ix_kernel::{constant::KConst, ingress::lean_ingress, tc::TypeChecker};

  let mut entries: Vec<_> =
    source.iter().map(|(name, ci)| (name.clone(), (*ci).clone())).collect();
  entries.sort_by_key(|(name, _)| name.pretty());
  for reverse in [false, true] {
    if reverse {
      entries.reverse();
    }
    let mut source = LeanEnv::default();
    for (name, ci) in &entries {
      source.insert(name.clone(), ci.clone());
    }
    let mut kenv = lean_ingress(&source).unwrap();
    let (block, _) =
      kenv.consts.iter().find(|(id, _)| &id.name == head).unwrap();
    let peers: Vec<_> = kenv.blocks[block]
      .iter()
      .filter(|id| matches!(kenv.consts.get(id), Some(KConst::Recr { .. })))
      .map(|id| id.name.clone())
      .collect();
    assert_eq!(
      peers, expected_peers,
      "recursors must follow source .all, not name or insertion order",
    );
    let mut ids: Vec<_> = kenv.consts.keys().cloned().collect();
    ids.sort_by_key(|id| id.name.pretty());
    for id in ids {
      TypeChecker::new(&mut kenv)
        .check_const(&id)
        .unwrap_or_else(|e| panic!("source fixture {}: {e}", id.name.pretty()));
    }
  }
}

#[test]
fn test_alpha_collapse_sort_consts_groups_inductives() {
  use crate::compile::{BlockCache, mk_indc, sort_consts};
  use crate::mutual::MutConst;
  use ix_common::env::ConstantInfo as LeanCI;

  let (env, a, b) = build_alpha_collapse_env();
  let stt = crate::compile::CompileState::default();
  let mut cache = BlockCache::default();

  let mut cs = Vec::new();
  for name in [&a, &b] {
    match env.get(name).as_deref() {
      Some(LeanCI::InductInfo(v)) => {
        cs.push(MutConst::Indc(
          mk_indc(v, &std::sync::Arc::new(env.clone())).unwrap(),
        ));
      },
      _ => panic!("missing inductive {}", name.pretty()),
    }
  }

  let refs: Vec<&MutConst> = cs.iter().collect();
  let classes = sort_consts(&refs, &mut cache, &stt).unwrap();
  assert_eq!(classes.len(), 1, "A and B should alpha-collapse to one class");
  let collapsed: Vec<Name> = classes[0].iter().map(|c| c.name()).collect();
  assert_eq!(collapsed.len(), 2);
  assert!(collapsed.contains(&a), "collapsed class should contain A");
  assert!(collapsed.contains(&b), "collapsed class should contain B");
}

#[test]
#[ignore = "expected to retire: members of one block no longer collapse"]
fn test_alpha_collapse_compile_env_addresses_inductives_and_ctors() {
  use crate::compile::env::compile_env;

  let (env, a, b) = build_alpha_collapse_env();
  let lean_env = std::sync::Arc::new(env);
  let stt = compile_env(&lean_env)
    .expect("compile_env should compile the minimal AlphaCollapse block");

  let a_addr = stt.resolve_addr(&a).expect("A should resolve");
  let b_addr = stt.resolve_addr(&b).expect("B should resolve");
  assert_eq!(a_addr, b_addr, "A and B should share one inductive address");

  let a_ctor = Name::str(a.clone(), "a".into());
  let b_ctor = Name::str(b.clone(), "b".into());
  let a_ctor_addr = stt.resolve_addr(&a_ctor).expect("A.a should resolve");
  let b_ctor_addr = stt.resolve_addr(&b_ctor).expect("B.b should resolve");
  assert_eq!(
    a_ctor_addr, b_ctor_addr,
    "A.a and B.b should share one constructor address",
  );
}

